import { readFile, readdir, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { zipSync, unzipSync } from 'fflate';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const dir = path.join(root, 'release-artifacts/jobs-extension');
await copyFile(path.join(root, 'extension/README.md'), path.join(dir, 'README.md'));
const entries = {}; for (const name of await readdir(dir)) entries[name] = new Uint8Array(await readFile(path.join(dir, name)));
const version = JSON.parse(new TextDecoder().decode(entries['manifest.json'])).version;
const archive = zipSync(entries, { level: 6 }), output = path.join(root, `release-artifacts/ResuLab-Jobs-Extension-${version}.zip`);
const extracted = unzipSync(archive); if (!extracted['manifest.json'] || !extracted['background.js']) throw new Error('Archive verification failed');
await writeFile(output, archive); console.log(output);
const downloads = path.join(root, 'public/downloads');
await mkdir(downloads, { recursive: true });
const filename = `ResuLab-Jobs-Extension-${version}.zip`;
await copyFile(output, path.join(downloads, filename));
const sha256 = createHash('sha256').update(archive).digest('hex');
await writeFile(path.join(downloads, 'extension.json'), JSON.stringify({ version, filename, url: `/downloads/${filename}`, bytes: archive.length, sha256 }, null, 2) + '\n');
console.log(`Public download: /downloads/${filename} (SHA256 ${sha256})`);
