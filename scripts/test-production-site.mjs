import { chromium, expect } from '@playwright/test';
import { createRequire } from 'node:module';
import { readFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('..',import.meta.url));
const require=createRequire(path.join(root,'server/package.json'));
const {serve}=require('@hono/node-server');
const {createSiteApp,loadLegacyApi}=await import('../server/dist/server/src/site.js');
const {createApp}=await import('../server/dist/server/src/app.js');
const {loadConfig}=await import('../server/dist/server/src/config.js');
const config=loadConfig({NODE_ENV:'test',ALLOWED_ORIGINS:'http://127.0.0.1:3186'});
const agent=createApp({config,modelReady:false,authenticate:async()=>{throw new Error('No fixture auth');}});
const site=createSiteApp({agent:req=>agent.fetch(req),legacy:await loadLegacyApi(config),staticRoot:path.join(root,'dist')});
const server=serve({fetch:site.fetch,hostname:'127.0.0.1',port:3186});
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
 await page.goto('http://127.0.0.1:3186/');
 await page.getByRole('link',{name:'下载扩展与安装说明 ↗',exact:true}).click();
 await expect(page).toHaveURL('http://127.0.0.1:3186/extension');
 const link=page.getByRole('link',{name:'下载浏览器扩展 ZIP ↓'});await expect(link).toBeVisible();
 const metadata=await (await page.request.get('http://127.0.0.1:3186/downloads/extension.json')).json();
 const pending=page.waitForEvent('download');await link.click();const download=await pending;
 assert.equal(download.suggestedFilename(),metadata.filename);
 const bytes=await readFile(await download.path());assert.equal(createHash('sha256').update(bytes).digest('hex'),metadata.sha256);
 for(const route of ['/api/ai/job-match','/api/ai/tailor','/api/account/delete','/api/agent/runs']) assert.equal((await page.request.post('http://127.0.0.1:3186'+route,{data:{}})).status(),401);
 assert.equal((await page.request.get('http://127.0.0.1:3186/downloads/missing.zip')).status(),404);
 const results=path.join(root,'docs/competition/results/production-site');await mkdir(results,{recursive:true});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(results,'extension-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(results,'extension-mobile.png'),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.getByRole('navigation',{name:'主导航',exact:true}).getByRole('link',{name:'求职工作台',exact:true}).click();
 await page.getByRole('link',{name:'下载扩展与安装说明 ↗',exact:true}).click();await expect(link).toBeVisible();
 console.log('PASS: production Node site routes, homepage/workbench download entry, real ZIP download and SHA256, auth guards, missing ZIP 404, desktop/mobile layout.');
} finally {await browser.close();await new Promise(resolve=>server.close(resolve));}
