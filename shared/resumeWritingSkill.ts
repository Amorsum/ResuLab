export function cosmeticContent(value: string | string[]): string {
  return (Array.isArray(value) ? value.join('\n') : value)
    .replace(/\.(?=\s|$)/g, '')
    .replace(/[\s,，。;；:：!！?？、“”‘’「」『』()（）【】\[\]·•]/gu, '');
}
